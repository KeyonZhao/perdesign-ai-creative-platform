type EcommercePosterPromptOptions = {
  productName?: string;
  userInstruction?: string;
};

const ECOMMERCE_SCENE_TEMPLATES = [
  [
    "人物交互型消费品",
    "仅适用于穿戴、手持、个护、运动或必须借助人体关系才能说明用途的产品。",
    "在使用模块中可加入人物或手部说明尺度与操作方式，但不得遮挡产品关键结构。"
  ],
  [
    "独立产品型消费品",
    "适用于桌面设备、家电、消费电子及无需人物说明的产品。",
    "使用桌面、家居或对应使用空间建立真实关系，以产品单独工作或静置的状态替代无意义的人物摆拍。"
  ],
  [
    "工业设备与专业工具",
    "适用于机械设备、仪器、检测设备、商用设备、专业工具与控制终端。",
    "使用可信的工作台、车间或专业环境；重点展示结构可靠性、操作区域、接口、安装和材质，禁止为了热闹加入无关人物。"
  ],
  [
    "安装环境型产品",
    "适用于灯具、安防、充电、建筑设备、嵌入式设备和基础设施部件。",
    "展示产品被正确安装后的真实关系，建筑或空间作为低干扰背景，产品仍需清晰、完整且占据主要视觉面积。"
  ],
  [
    "零部件、材料与系统组件",
    "适用于连接器、模组、面板、零部件、材料样件和系统组件。",
    "使用微距英雄图、整齐阵列或必要的结构关系展示；只有原图能证明时才可表现装配关系，禁止虚构内部结构、数量、规格或应用方式。"
  ]
] as const;

export function buildEcommercePosterPrompt({ productName, userInstruction }: EcommercePosterPromptOptions) {
  const normalizedProductName = productName?.trim();
  const normalizedUserInstruction = userInstruction?.trim();
  const templateText = ECOMMERCE_SCENE_TEMPLATES
    .map(([name, scope, direction], index) => `${index + 1}. ${name}：${scope}${direction}`)
    .join("\n");

  return [
    "任务：根据输入的产品设计图，生成一张完整的纵向电商详情长图，而不是单张产品主视觉海报。",
    normalizedProductName ? `已知产品名称：${normalizedProductName}。` : "",
    normalizedUserInstruction
      ? `用户补充要求（在不改变产品结构、不虚构参数的前提下优先执行）：${normalizedUserInstruction}`
      : "",
    "",
    "一、产品还原是最高优先级",
    "输入图片中的产品是唯一设计依据。准确保留产品品类、整体轮廓、比例、体块关系、结构分区、操作界面、接口、按键、旋钮、孔位、分缝、材质边界、颜色关系和品牌标识。",
    "不得把产品重新设计成另一款产品，不得擅自增加、删除、移动或复制结构与功能件。只允许提升灯光、材质表现、画面完成度和商业展示质感。",
    "长图中所有主图、角度图、细节图、场景图和使用图必须表现同一款产品，造型、配色、材质、按钮、接口和标识前后一致，禁止每个模块生成不同产品。",
    "",
    "二、纵向长图叙事结构",
    "画布使用 9:16 纵向长图比例，自上而下形成 4 至 6 个宽幅叙事章节。不要把页面切成许多尺寸相同的小卡片，也不要让每个章节都机械重复完整产品。",
    "章节 1｜首屏产品主视觉：使用最大面积展示产品三分之四视角或最能说明造型的角度，产品完整醒目，并同步建立整张长图的背景、配色、字体和光影基调。",
    "章节 2｜核心价值视觉化：围绕产品最重要的使用价值或用户指定内容，生成具有解释力的概念渲染。这里可以不出现完整产品，可使用气流、热量路径、粒子轨迹、光效、能量流、材料肌理、结构示意、功能图标或芯片意象等视觉语言。",
    "章节 3｜关键设计与性能细节：将真实产品局部特写与概念化性能画面穿插排布，选择 2 至 4 个最能建立说服力的结构、材质、接口、按键、工艺或工作原理。",
    "章节 4｜真实使用或安装场景：根据品类展示合理的握持、佩戴、摆放、操作、连接、安装或工作环境。不需要人与产品交互时，使用设备运行状态、安装关系或专业环境。",
    "章节 5｜价值收束：使用一张有氛围的产品图、场景图或礼赠/部署画面完成收尾，让产品价值和目标用户自然落地。",
    "章节数量可根据产品信息合并或调整，但整张长图应同时具备产品展示、价值解释、细节或原理、应用场景和清晰文案。",
    "",
    "性能概念画面规则：",
    "允许为了说明功能和性能生成并非产品照片的概念渲染，例如风道、扇叶运动、散热路径、芯片算力、流体、声波、光路、材料截面或结构原理画面。",
    "这类画面用于视觉解释，不代表已经验证的真实内部结构。不得把无法确认的部件画成精确拆机结构，不得附加未经用户提供的性能数字、认证标志、测试结果或绝对化结论。",
    "用户明确提供了功能、卖点或性能要求时，应优先将其转化为直观的概念画面和简洁文案；只有产品图而没有性能资料时，使用不带具体数字的品类级价值表达。",
    "",
    "三、根据品类选择合适的场景模板",
    templateText,
    "不要在画面中输出模板名称。不要机械使用人物；只有人物确实能解释尺度、操作或使用关系时才允许出现。",
    "",
    "四、视觉连续性与排版规则",
    "最终只输出一张完整连续的纵向长图。它可以包含多个上下展开的叙事章节，但不是四宫格，不是若干独立方案，也不是杂乱图片拼贴。",
    "使用专业商业摄影或高品质产品渲染语言：干净的主光、自然的接触阴影、清晰的材质层次、克制的背景与明确的视觉层级。",
    "背景和道具只能帮助说明品类、尺度、安装方式或使用环境，不得抢夺主体，不得堆砌无关装饰。",
    "首屏必须有强主视觉，中段通过图像尺度、背景明暗和视觉动线变化形成阅读节奏。相邻章节使用共享背景色、柔和色彩过渡、光影延伸、图形叠层、局部重叠或留白完成衔接。",
    "禁止在每张图之间使用贯穿全宽的白色分割线，禁止大量白边、等宽卡片边框和过度零碎的豆腐块排版。只有信息层级确实需要时才使用少量细线或色块。",
    "不得出现网页按钮、轮播箭头、浏览器界面或交互控件。",
    "",
    "五、必须生成适量文案",
    normalizedProductName
      ? `首屏可使用“${normalizedProductName}”作为产品名称，并围绕用户要求和图中可确认的信息撰写卖点文案。`
      : "根据产品品类和用户补充要求撰写简洁、可信的品类级文案，不要杜撰品牌名。",
    "首屏应有一组醒目的主标题与短副标题；中段每个主要章节使用一个短标题，并可搭配一句简短解释。文案应放在画面留白、色块或低干扰背景上，与对应视觉内容就近关联。",
    "文案要体现使用价值和用户收益，不要只写空泛的“科技感、品质感、创新设计”。没有可靠数据时使用定性表达，不生成具体数字。",
    "禁止虚构认证、奖项、功能、参数、价格、促销信息、品牌口号和绝对化承诺。原图已有品牌文字应尽量准确保留。",
    "文字必须清晰、完整、无乱码，避免小到无法阅读的密集长段落；以短句、短标题和少量图标标签为主。",
    "",
    "六、质量限制",
    "禁止产品结构错误、跨模块造型漂移、颜色漂移、重复部件、悬浮错位、接口变形、品牌乱码、人物手部错误、过度景深、杂乱背景、低清晰度和廉价模板感。",
    "最终只输出完成后的纵向电商详情长图，不输出分析过程、模板说明或额外文字。"
  ].filter(Boolean).join("\n");
}
