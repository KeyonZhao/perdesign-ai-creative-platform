/** Shared by prompt writing and image generation so neither stage locks the old exterior. */
export function buildStructureDesignInstruction(innovationLevel = 50) {
  const level = Math.max(0, Math.min(100, innovationLevel));
  const direction = level <= 30
    ? "外壳采用简洁克制的完整包覆与统一曲面，不是给原结构换色。"
    : level <= 70
      ? "外壳形成鲜明的新轮廓、连贯曲面和统一体块，不逐件描摹内部零件。"
      : "大胆探索外壳轮廓、曲面转折、包覆关系与分件，但不得移动或缩放内部器件来迁就造型。";
  return [
    "结构图模式：第一张图是内部结构与空间布局依据，不是外观成品或需要复刻的轮廓。任务是在其外围设计全新、完整的产品外壳，而不是原结构美化、换材质或重新渲染。",
    "保持可见器件的体量、相对位置、安装接口及必要功能空间；不能擅自移动、缩小、删除或替换内部组件。镜头视野、传感器扫描、运动、散热和操作区域按实际可见信息合理避让，不用壳体遮挡或填满功能开口。未提供的尺寸、内部结构和功能不得臆造。",
    "将支架、连接板和非功能性裸露结构组织在统一外壳内，不把它们的轮廓、孔洞和筋条逐一复制到外表面。允许改变外壳外轮廓、曲面、包覆和分件；必要的工作部件保持外露，不是把所有器件封进盒子。",
    `创新度${level}%只控制外壳造型，不放宽内部布局约束。${direction}`,
    "用户明确指定的保留或修改区域优先，尽量保留原观察方向以便核对内部关系。若有后续参考图，仅借鉴其适合的造型语言和CMF，不复制其产品或内部布局。只表现视觉设计方案，不宣称已完成尺寸、干涉或可制造性验证。"
  ].join("\n");
}
